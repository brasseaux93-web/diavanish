export const LEDGER_STRINGS: Record<LedgerLang, Record<LedgerKey, string>> = { en, fr, es, ar };

export function ledgerT(lang: LedgerLang, key: LedgerKey, vars?: Record<string, string | number>): string {
  let s = LEDGER_STRINGS[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
