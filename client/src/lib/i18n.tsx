import { fr } from "./locales/fr";
import { es } from "./locales/es";
// Structured record (ledger v2). fr, es and ar there are flagged for native review.
import { LEDGER_STRINGS } from "@shared/ledger-i18n";

export const dicts: Record<Lang, Record<string, string>> = {
  en: { ...en, ...LEDGER_STRINGS.en },
  ar: { ...ar, ...LEDGER_STRINGS.ar },
  fr: { ...fr, ...LEDGER_STRINGS.fr },
  es: { ...es, ...LEDGER_STRINGS.es },
};

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  dir: "ltr" | "rtl";
};

const I18nContext = createContext<Ctx>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
  dir: "ltr",
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.classList.toggle("dir-rtl", lang === "ar");
  }, [lang]);

  const t = (key: string, vars?: Record<string, string | number>) => {
    let s = dicts[lang][key] ?? dicts.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    }
    return s;
  };

  return (
    <I18nContext.Provider
      value={{ lang, setLang: setLangState, t, dir: lang === "ar" ? "rtl" : "ltr" }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
